#!/usr/bin/env python3
"""
Writes the store's app icon (Admin → Company setup → App icon, else the logo) into the app as its launcher icon.
Android launcher icons are compiled into the APK, so the release workflow runs this before every build.

    python3 scripts/brand_icon.py --api https://shop.example.com/          # icon from the live server
    python3 scripts/brand_icon.py --file logo.png --background "#0b1f4b"   # a local image instead

Needs Pillow (pip install pillow). Exits without changing anything when the store has no icon or logo yet,
so the built-in icon stays.
"""
import argparse
import io
import json
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

from PIL import Image

RES = Path(__file__).resolve().parent.parent / "app" / "src" / "main" / "res"
# Adaptive icon foreground is 108dp; only the centre 66dp is guaranteed visible, so the artwork fills ~60%.
FG = 432
ART = round(FG * 0.6)
MAX_BYTES = 10 * 1024 * 1024


def fetch(url: str) -> bytes:
    if not url.startswith("https://") and not url.startswith("http://"):
        raise SystemExit(f"Refusing to download {url!r}: not an http(s) URL")
    req = urllib.request.Request(url, headers={"User-Agent": "suvrnika-android-build", "Accept": "*/*"})
    with urllib.request.urlopen(req, timeout=30) as r:
        data = r.read(MAX_BYTES + 1)
    if len(data) > MAX_BYTES:
        raise SystemExit(f"{url} is larger than 10 MB")
    return data


def icon_from_api(api: str) -> tuple[str, bytes] | None:
    base = api if api.endswith("/") else api + "/"
    config = json.loads(fetch(base + "api/v1/config"))
    company = config.get("company") or {}
    url = company.get("appIconUrl") or company.get("logoUrl") or ""
    if not url:
        return None
    url = urllib.parse.urljoin(base, url)  # /media/… paths are relative to the server
    return url, fetch(url)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--api", help="server base URL, e.g. https://shop.example.com/")
    src.add_argument("--file", help="local image")
    ap.add_argument("--background", default="#FFFFFF", help="launcher background colour (default white)")
    args = ap.parse_args()
    if not re.fullmatch(r"#[0-9a-fA-F]{6}", args.background):
        raise SystemExit("--background must be a hex colour like #FFFFFF")

    if args.file:
        label, data = args.file, Path(args.file).read_bytes()
    else:
        found = icon_from_api(args.api)
        if not found:
            print("No app icon or logo is set in Admin → Company setup; keeping the built-in launcher icon.")
            return
        label, data = found

    art = Image.open(io.BytesIO(data)).convert("RGBA")
    art.thumbnail((ART, ART), Image.LANCZOS)
    foreground = Image.new("RGBA", (FG, FG), (0, 0, 0, 0))
    foreground.paste(art, ((FG - art.width) // 2, (FG - art.height) // 2), art)

    (RES / "drawable-nodpi").mkdir(parents=True, exist_ok=True)
    foreground.save(RES / "drawable-nodpi" / "ic_launcher_brand.png", optimize=True)
    (RES / "values" / "ic_launcher_brand.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_brand_background">{args.background}</color>\n</resources>\n'
    )
    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by scripts/brand_icon.py from the store's app icon. -->\n"
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_brand_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_brand" />\n'
        "</adaptive-icon>\n"
    )
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (RES / "mipmap-anydpi-v26" / name).write_text(adaptive)
    print(f"Launcher icon generated from {label}.")


if __name__ == "__main__":
    try:
        main()
    except urllib.error.URLError as e:
        sys.exit(f"Could not download the icon: {e}")
